import { Translation } from '@strengthos/shared-i18n';

/**
 * Helper function to create Translation objects with default metadata
 * This reduces file size by eliminating redundant metadata in each entry
 * Automatically sets the key from the property name if not provided
 */
function createTranslationHelper(locale: string) {
  const defaultDate = new Date('2024-01-01');
  return (value: string, key?: string, version = 1): Translation => ({
    locale,
    key: key || '',
    value,
    lastUpdated: defaultDate,
    version,
  });
}

const t = createTranslationHelper('en-US');

/**
 * Post-process translations to automatically set keys from property names
 * This ensures all translation objects have the correct key even if not explicitly provided
 */
function setTranslationKeys(
  translations: Record<string, Translation>,
): Record<string, Translation> {
  const result: Record<string, Translation> = {};
  for (const [key, translation] of Object.entries(translations)) {
    result[key] = { ...translation, key: translation.key || key };
  }
  return result;
}

