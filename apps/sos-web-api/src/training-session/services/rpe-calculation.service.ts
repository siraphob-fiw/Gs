  /**
   * Calculate the percentage of 1RM based on reps and RPE
   * @param reps Number of reps performed
   * @param rpe Rate of Perceived Exertion (1-10)
   * @returns Percentage of 1RM (0-1)
   */
  getRPEPercentage(reps: number, rpe: number): number {
    if (this.LOAD_CAPACITY_CHART[rpe]?.[reps]) {
      return this.LOAD_CAPACITY_CHART[rpe][reps];
    }
  }
  /**
   * Calculate estimated 1RM from weight, reps, and RPE
   * Result is rounded to nearest 0.5
   */
  calculate1RM(weight: number, reps: number, rpe: number): number {
    if (weight <= 0 || reps <= 0 || rpe > 10) {
      return 0;
    }

    const opPercent = this.getRPEPercentage(reps, rpe);
    const oneRM = (weight / opPercent) * 100;
    if (oneRM <= 0) {
      return 0;
    }
    // Round to nearest 0.5
    return oneRM;
  }
